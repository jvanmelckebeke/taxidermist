// Package docs renders the docs folder, <taxonomy>/format/ by default: one page per doctype with a fill-in template
// and every vocabulary it uses, and one page per vocabulary under vocabularies/.
//
// The schema is split across several files so each stays readable, and that split is
// what makes "what does this doctype need?" a multi-file question. These pages resolve
// it, so writing frontmatter is one read. They are generated: edit the schema and
// re-run, and `docs --check` fails while a page is stale.
package docs

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/jvanmelckebeke/taxidermist/internal/schema"
)

// HouseRules is the hand-written file whose text leads the index page's rules.
const HouseRules = "house-rules.md"

// bannerText marks a page as generated. Sync refuses to touch a folder holding a
// markdown file without it.
const bannerText = "GENERATED by taxidermist"

func banner(s *schema.Schema) string {
	return "<!-- " + bannerText + " from " + filepath.Base(s.Dir) +
		"/. Do not hand-edit: edit the schema and run `" + s.Command("docs") + "`. -->"
}

// up is the path from a page nested depth folders below the docs folder (0 is the
// README, 1 a vocabulary page) to dir, with a trailing slash unless it is the page's
// own folder. Every link a page makes to the schema or the repo goes through it, so
// the docs folder can sit anywhere.
func up(s *schema.Schema, depth int, dir string) string {
	from := s.DocsDir
	for range depth {
		from = filepath.Join(from, "x")
	}
	r, err := filepath.Rel(from, dir)
	if err != nil || r == "." {
		return ""
	}
	return filepath.ToSlash(r) + "/"
}

// toSchema links a file in the schema folder, from a page in the docs folder.
func toSchema(s *schema.Schema, depth int, rel string) string { return up(s, depth, s.Dir) + rel }

// toBase links a path relative to the config's folder.
func toBase(s *schema.Schema, depth int, rel string) string { return up(s, depth, s.Base) + rel }

// readmeLink links the schema directory by name, to its README when it has one. It is
// used on the index page and on type pages, both directly in the docs folder.
func readmeLink(s *schema.Schema) string {
	name := filepath.Base(s.Dir) + "/"
	if _, err := os.Stat(filepath.Join(s.Dir, "README.md")); err == nil {
		return "[" + name + "](" + toSchema(s, 0, "README.md") + ")"
	}
	return "[" + name + "](" + strings.TrimSuffix(up(s, 0, s.Dir), "/") + ")"
}

// Unbannered lists the markdown files in the docs folder, and its vocabularies/ folder,
// that carry no generated banner. Sync would delete them, so it refuses instead.
func Unbannered(s *schema.Schema) []string {
	var out []string
	for _, pat := range []string{"*.md", VocabularyDir + "/*.md"} {
		files, _ := filepath.Glob(filepath.Join(s.DocsDir, pat))
		for _, p := range files {
			if b, err := os.ReadFile(p); err == nil && !strings.Contains(string(b), bannerText) {
				out = append(out, p)
			}
		}
	}
	sort.Strings(out)
	return out
}

// Pages returns page name (without .md) -> body, including the README index.
func Pages(s *schema.Schema) (map[string]string, error) {
	out := map[string]string{}
	for _, dt := range s.Doctypes() {
		t := s.Types[dt]
		out[t.Slug] = render(s, t)
	}
	idx, err := indexPage(s)
	if err != nil {
		return nil, err
	}
	out["README"] = idx
	for _, v := range s.VocabularyNames() {
		out[VocabularyDir+"/"+v] = vocabularyPage(s, v)
	}
	return out, nil
}

// Sync writes the pages, or with check set reports the stale ones and writes nothing.
// A page on disk that no doctype generates is stale too, and is deleted on a write.
func Sync(s *schema.Schema, check bool) (stale []string, written, total int, err error) {
	out := s.DocsDir
	if hand := Unbannered(s); len(hand) > 0 {
		return nil, 0, 0, fmt.Errorf("%s holds hand-written markdown (%s) and docs would delete it. "+
			"Point `docs:` in %s at a folder of its own.", schema.Display(out), schema.Display(hand[0]), s.ConfigName)
	}
	pages, err := Pages(s)
	if err != nil {
		return nil, 0, 0, err
	}
	if !check {
		if err := os.MkdirAll(out, 0o755); err != nil {
			return nil, 0, 0, err
		}
	}
	names := make([]string, 0, len(pages))
	for n := range pages {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, name := range names {
		p := filepath.Join(out, filepath.FromSlash(name)+".md")
		body := strings.TrimRight(pages[name], "\n") + "\n"
		if cur, err := os.ReadFile(p); err == nil && string(cur) == body {
			continue
		}
		if check {
			stale = append(stale, p)
			continue
		}
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return nil, 0, 0, err
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			return nil, 0, 0, err
		}
		written++
	}
	existing, _ := filepath.Glob(filepath.Join(out, "*.md"))
	vocab, _ := filepath.Glob(filepath.Join(out, VocabularyDir, "*.md"))
	existing = append(existing, vocab...)
	sort.Strings(existing)
	for _, p := range existing {
		rel, _ := filepath.Rel(out, p)
		if _, ok := pages[strings.TrimSuffix(filepath.ToSlash(rel), ".md")]; ok {
			continue
		}
		if check {
			stale = append(stale, p)
		} else if err := os.Remove(p); err != nil {
			return nil, 0, 0, err
		}
	}
	return stale, written, len(pages), nil
}
